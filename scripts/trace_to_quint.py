#!/usr/bin/env python3
"""Turn a lab run's transition log into a Quint run of formal/ue.qnt.

    scripts/trace_to_quint.py test/results/<run>/ue.log > formal/trace.qnt
    quint test formal/trace.qnt --main=trace

Every state change of the declared machines is logged as
`<MACHINE> <from> → <to> on <event> [<clause>]` (ferrite_common::fsm). The
lines of the machines the model composes (RRC, 5GMM, 5GMM-CM, Connection)
are mapped onto the model's actions; `quint test` then replays them from
`init`, failing at the first step the model does not allow and checking the
model's invariants after every step. That checks the model against what the
UE did, and the UE's behaviour against the model's properties. The replay
stops at the first transition the model does not cover (a service request,
the deregistration on exit, re-establishment) and says so.
"""

import re
import sys

LINE = re.compile(
    r"\] (RRC|5GMM|5GMM-CM|Connection) (\S+) → (\S+) on (\w+) \["
)


def actions(lines):
    """(action, source line) pairs, and why the replay stopped (or None)."""
    out = []
    events = []
    for n, line in enumerate(lines, 1):
        m = LINE.search(line)
        if m:
            events.append((n, *m.groups()))
    started = False
    i = 0
    while i < len(events):
        n, machine, frm, to, ev = events[i]
        nxt = events[i + 1] if i + 1 < len(events) else None
        i += 1
        if machine == "5GMM-CM":
            continue  # follows RRC in the model
        if machine == "Connection":
            if ev == "Connect":
                out.append(("nasConnect" if started else "cellConfigured", n))
                started = True
            continue  # Established / Released / Failed follow RRC
        if machine == "RRC":
            if (frm, to) == ("Connecting", "Connected"):
                out.append(("rrcSetup", n))
            elif (frm == "Connecting" and to == "Idle") or (
                (frm, to) == ("Connected", "Idle") and ev == "RadioLinkFailure"
            ):
                # The NAS lower-layer failure that follows belongs to the
                # same model step.
                out.append(("establishmentFailure" if frm == "Connecting" else "rlf", n))
                while (
                    i < len(events)
                    and events[i][1] in ("5GMM", "5GMM-CM", "Connection")
                    and events[i][4] in ("RegistrationFailed", "ConnectionReleased", "Failed")
                ):
                    i += 1
            elif (frm, to) == ("Connected", "Idle") and ev == "Release":
                out.append(("release", n))
            elif frm == "Idle" and to == "Connecting":
                continue  # the Connection line carries it
            else:
                return out, f"line {n}: RRC {frm} → {to} on {ev} is not modelled"
            continue
        # 5GMM
        if ev == "RegistrationRequested":
            if frm.startswith("Deregistered(AttemptingRegistration)"):
                out.append(("retryTimerExpiry", n))
            elif not started:
                continue  # the first one is part of cellConfigured
            elif nxt and nxt[1] == "Connection":
                continue
            else:
                return out, f"line {n}: 5GMM {frm} → {to} on {ev} is not modelled"
        elif ev == "AuthenticationCompleted":
            continue  # folded into coreSecurity
        elif ev == "SecurityModeCompleted":
            out.append(("coreSecurity", n))
        elif ev == "RegistrationAccepted":
            out.append(("coreAccept", n))
        elif ev == "RegistrationFailed":
            out.append(("t3510Expiry", n))
        elif ev == "SwitchOff":
            out.append(("switchOff", n))
        elif ev == "RegistrationRejected" and to == "Deregistered(NoSupi)":
            out.append(("coreRejectNoSupi", n))
        elif ev == "RegistrationRejected":
            out.append(("coreRejectAbnormal", n))
        else:
            return out, f"line {n}: 5GMM {frm} → {to} on {ev} is not modelled"
    return out, None


def main():
    path = sys.argv[1]
    with open(path, encoding="utf-8", errors="replace") as f:
        acts, stop = actions(f.readlines())
    steps = "".join(
        f"\n      .then({a}).expect(allProps) // ue.log:{n}" for a, n in acts
    )
    print(f"// Generated by scripts/trace_to_quint.py from {path}")
    print(f"// {len(acts)} steps" + (f"; replay stops at {stop}" if stop else ""))
    print("module trace {")
    print('  import ue(FIXED = true).* from "./ue"')
    print(f"  run replayTest = init.expect(allProps){steps}")
    print("}")
    print(f"{len(acts)} steps" + (f"; stopped at {stop}" if stop else "; whole log"), file=sys.stderr)


if __name__ == "__main__":
    main()
